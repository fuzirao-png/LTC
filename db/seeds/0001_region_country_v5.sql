INSERT INTO ltc.ref_region_country (
    country_code, country_name, region_code, subregion, default_timezone, data_version, note
)
SELECT country_code, country_name, region_code, subregion, default_timezone, data_version, note
FROM ltc_region_country_seed
ON CONFLICT (country_code) DO UPDATE SET
    country_name = EXCLUDED.country_name,
    region_code = EXCLUDED.region_code,
    subregion = EXCLUDED.subregion,
    default_timezone = EXCLUDED.default_timezone,
    data_version = EXCLUDED.data_version,
    note = EXCLUDED.note;

DELETE FROM ltc.ref_region_country existing
WHERE NOT EXISTS (
    SELECT 1
    FROM ltc_region_country_seed seed
    WHERE seed.country_code = existing.country_code
);

COMMIT;
