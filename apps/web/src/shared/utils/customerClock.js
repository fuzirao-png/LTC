const CITY_NAMES_BY_NORMALIZED = {
  BERLIN: '\u67cf\u6797',
  TOKYO: '\u4e1c\u4eac',
  SINGAPORE: '\u65b0\u52a0\u5761',
  GLOBAL: '\u57ce\u5e02\u5f85\u786e\u8ba4',
};

const COUNTRY_ISO_BY_NAME = Object.fromEntries(
  Object.values(COUNTRY_CLOCKS_BY_ISO).map((entry) => [entry.countryName.toUpperCase(), entry.countryCode]),
);

function normalizeCountry(value) {
  return String(value || '').trim().replace(/\s+/g, ' ').toUpperCase();
}

function countryClockEntry(country) {
  const key = normalizeCountry(country);
  const countryCode = COUNTRY_CLOCKS_BY_ISO[key]
    ? key
    : COUNTRY_ALIASES[key] || COUNTRY_ISO_BY_NAME[key];
  return countryCode ? COUNTRY_CLOCKS_BY_ISO[countryCode] : null;
}

export function countryNameFor(country) {
  return countryClockEntry(country)?.countryName || '';
}

export function countryCardLabel(country) {
  return countryNameFor(country) || '国家待确认';
}

export function regionCodeForCountry(country) {
  return countryClockEntry(country)?.regionCode || '';
}

export function cityNameFor(city) {
  const cityText = String(city || '').trim();
  if (!cityText) return '';
  return CITY_NAMES_BY_NORMALIZED[cityText.toUpperCase()] || cityText;
}

export function resolveCustomerClock(customer) {
  const entry = countryClockEntry(customer?.country);
  const explicitTimeZone = String(customer?.timeZone || '').trim();
  if (explicitTimeZone) {
    return {
      countryCode: entry?.countryCode || '',
      countryName: entry?.countryName || '',
      regionCode: entry?.regionCode || '',
      label: entry ? `${entry.countryName}时间` : '当地时间',
      timeZone: explicitTimeZone,
    };
  }
  if (!entry) return null;
  return { ...entry, label: `${entry.countryName}时间` };
}
