import asyncio
from datetime import datetime, timezone
from typing import Any
from uuid import uuid4

from ltc.modules.customer_operation.infrastructure.email_provider_adapter import SmtpEmailClient
from ltc.modules.customer_operation.infrastructure.email_draft_store import EmailDraftStore
from ltc.modules.customer_operation.infrastructure.email_context_builder import build_email_generation_memory
from ltc.modules.customer_operation.infrastructure.legacy_file_store import LegacyFileStore
from ltc.modules.customer_operation.infrastructure.mail_store import PostgresMailStore
from ltc.modules.customer_operation.application.skills_registry import SKILL_REGISTRY
from ltc.modules.customer_operation.application.analysis_trigger import (
    trigger_customer_analysis_best_effort,
)


async def generate_email_for_payload(payload: dict[str, Any]) -> dict[str, Any]:
    context = build_email_generation_memory(payload)
    draft = await SKILL_REGISTRY["email_generate"].run(context)
    return {
        "success": True,
        "subject": draft["subject"],
        "body": draft["body"],
        "model": draft.get("model") or "",
        "message": "Email generated by customer operation agent.",
    }


async def translate_email_for_payload(payload: dict[str, Any]) -> dict[str, Any]:
    translated = await SKILL_REGISTRY["email_translate"].run(payload)
    return {
        "success": True,
        "language": translated["language"],
        "translatedSubject": translated["translatedSubject"],
        "translatedText": translated["translatedText"],
        "model": translated.get("model") or "",
        "message": "Email translated by customer operation agent.",
    }


async def send_email_for_payload(payload: dict[str, Any]) -> dict[str, Any]:
    draft_id = str(payload.get("draftId") or payload.get("draft_id") or "").strip()
    user_id = str(payload.get("userId") or payload.get("user_id") or "").strip()
    company_id = str(payload.get("companyId") or payload.get("company_id") or "").strip()
    contact_id = str(payload.get("contactId") or payload.get("contact_id") or "").strip()
    customer_name = str(payload.get("customerName") or "").strip()
    recipient_name = str(payload.get("recipientName") or "").strip()
    recipient_email = str(payload.get("recipientEmail") or payload.get("to") or "").strip()
    subject = str(payload.get("subject") or "").strip()
    body = str(payload.get("body") or "").strip()
    purpose = str(payload.get("purpose") or "first_touch").strip()
    draft_store = None
    if draft_id:
        if not user_id:
            raise ValueError("userId is required when sending a draft")
        draft_store = EmailDraftStore()
        draft = draft_store.get(email_id=draft_id, sales_user_id=user_id)
        if not draft or draft.get("status") != "draft":
            raise ValueError("Email draft not found")
        draft_company_id = str(draft.get("company_id") or "")
        if company_id and company_id != draft_company_id:
            raise ValueError("Draft does not belong to the requested company")
        company_id = draft_company_id
        contact_id = str(draft.get("contact_id") or "")
        subject = str(draft.get("subject") or "").strip()
        body = str(draft.get("body_text") or "").strip()
        purpose = str(draft.get("purpose") or "first_touch").strip()
    if purpose not in {"first_touch", "reply_followup", "meeting_followup"}:
        raise ValueError("purpose must be one of: first_touch, reply_followup, meeting_followup")

    if bool(company_id) != bool(contact_id):
        raise ValueError("companyId and contactId must be provided together")
    if company_id and contact_id:
        customer_name, recipient_name, recipient_email = PostgresMailStore().resolve_outbound_target(
            company_id, contact_id, purpose
        )

    if draft_store is not None:
        attachments = draft_store.attachment_payloads(
            email_id=draft_id, sales_user_id=user_id
        )
    else:
        attachments = payload.get("attachments")
        if not isinstance(attachments, list):
            attachments = []

    missing = [
        name
        for name, value in {
            "customerName": customer_name,
            "recipientName": recipient_name,
            "recipientEmail": recipient_email,
            "subject": subject,
            "body": body,
        }.items()
        if not value
    ]
    if missing:
        raise ValueError(f"Missing required fields: {', '.join(missing)}")

    try:
        delivery = await SmtpEmailClient(user_id=user_id).send(
            recipient_email=recipient_email,
            subject=subject,
            body=body,
            attachments=attachments,
        )
    except Exception as exc:
        if draft_store is not None:
            raise
        postgres_store = PostgresMailStore()
        if postgres_store.is_configured():
            postgres_store.record_failed_outbound_email(
                customer_name=customer_name,
                recipient_name=recipient_name,
                recipient_email=recipient_email,
                subject=subject,
                body=body,
                purpose=purpose,
                error_message=str(exc),
                source=str(payload.get("source") or "customer-operation-email").strip(),
                company_id=company_id,
                contact_id=contact_id,
            )
        raise
    record = {
        "id": str(uuid4()),
        "customerName": customer_name,
        "recipientName": recipient_name,
        "intendedTo": recipient_email,
        "deliveredTo": delivery["deliveredTo"],
        "subject": subject,
        "body": body,
        "purpose": purpose,
        "mode": delivery["mode"],
        "provider": delivery["provider"],
        "smtpStatus": delivery.get("smtpStatus", "submitted"),
        "deliveryStatus": delivery.get("deliveryStatus", "unconfirmed"),
        "deliveryConfirmed": bool(delivery.get("deliveryConfirmed", False)),
        "createdAt": datetime.now(timezone.utc).isoformat(),
        "messageId": delivery["messageId"],
        "attachments": [
            {
                "filename": str(item.get("filename") or ""),
                "contentType": str(item.get("contentType") or ""),
                "size": int(item.get("size") or 0),
            }
            for item in attachments
        ],
        "customerId": str(payload.get("customerId") or "").strip(),
        "recipientId": str(payload.get("recipientId") or "").strip(),
        "source": str(payload.get("source") or "customer-operation-email").strip(),
    }
    LegacyFileStore().append_mail_record(record)
    try:
        postgres_store = PostgresMailStore()
        if draft_store is not None:
            if not draft_store.mark_sent(
                email_id=draft_id, sales_user_id=user_id, delivery=delivery
            ):
                raise RuntimeError("Email draft could not be marked as sent")
            record["companyId"] = company_id
            record["contactId"] = contact_id
            record["emailId"] = draft_id
            trigger_customer_analysis_best_effort(company_id, source="outbound_email")
        elif postgres_store.is_configured():
            stored = postgres_store.record_outbound_email(
                customer_name=customer_name,
                recipient_name=recipient_name,
                recipient_email=recipient_email,
                subject=subject,
                body=body,
                purpose=purpose,
                delivery=delivery,
                attachments=attachments,
                source=str(payload.get("source") or "customer-operation-email").strip(),
                user_id=user_id,
                company_id=company_id,
                contact_id=contact_id,
            )
            record["companyId"] = stored.company_id
            record["contactId"] = stored.contact_id
            record["emailId"] = stored.email_id
            if stored.company_id:
                trigger_customer_analysis_best_effort(
                    stored.company_id,
                    source="outbound_email",
                )
    except Exception as exc:
        if draft_store is not None:
            raise
        record["dbError"] = str(exc)
    return {
        "success": True,
        "messageId": delivery.get("messageId") or record.get("messageId") or "",
        "message": (
            f"SMTP submission accepted for {delivery['deliveredTo']}; delivery is not yet confirmed."
            if delivery["mode"] != "test-relay"
            else f"Test relay accepted the message for {delivery['deliveredTo']}."
        ),
        "smtpStatus": delivery.get("smtpStatus", "submitted"),
        "deliveryStatus": delivery.get("deliveryStatus", "unconfirmed"),
        "deliveryConfirmed": bool(delivery.get("deliveryConfirmed", False)),
        "record": record,
    }

