def normalize_scene_code(value: str | None) -> str:
    code = str(value or "").strip().upper()
    aliases = {"TMC": "S1", "TRAVEL_PLATFORM": "S1", "TRAVEL_OTA": "S2", "OTA": "S2", "FINTECH": "S3", "OTHER": "S4"}
    code = aliases.get(code, code)
    return code if code in SCENE_CODES else "S4"


def hard_gate_passed(scores: dict[str, float]) -> bool:
    return float(scores.get("D1", 0)) > 0
