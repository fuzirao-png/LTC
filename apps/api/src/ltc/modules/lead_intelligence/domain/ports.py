"""Ports used by the lead intelligence application layer."""

from __future__ import annotations

from typing import Any, Protocol

from .models import CompanyCandidate, DimensionScore, SearchRequest


class MemoryPort(Protocol):
    def read(self, request: SearchRequest) -> list[dict[str, Any]]: ...
    def write(self, request: SearchRequest, candidate: CompanyCandidate) -> None: ...


class SearchProviderPort(Protocol):
    code: str

    def search(self, query: str, *, phase: str, limit: int = 20) -> list[dict[str, Any]]: ...


class CompanyLookupPort(Protocol):
    def lookup(self, *, company_name: str, country: str | None = None, company_domain: str | None = None) -> dict[str, Any]: ...


class ContactLookupPort(Protocol):
    def lookup(self, *, company_url: str) -> list[dict[str, Any]]: ...


class LanguageModelPort(Protocol):
    def plan_query(self, *, request: SearchRequest, memory: list[dict[str, Any]]) -> str: ...

    def extract_candidates(self, *, request: SearchRequest, results: list[dict[str, Any]], memory: list[dict[str, Any]]) -> list[dict[str, Any]]: ...

    def summarize_missing(self, *, request: SearchRequest, candidate: dict[str, Any], leads_finder: dict[str, Any]) -> dict[str, Any]: ...

    def summarize_company(self, *, request: SearchRequest, candidate: dict[str, Any], company_evidence: dict[str, Any], contacts: list[dict[str, Any]], exa_evidence: list[dict[str, Any]]) -> dict[str, Any]: ...

    def score_dimension(self, *, candidate: dict[str, Any], dimension_code: str, evidence: list[dict[str, Any]], score_type: str, scene_code: str = "S1") -> DimensionScore: ...


class LeadRepositoryPort(Protocol):
    def create_search_run(self, request: SearchRequest) -> tuple[str, str]: ...
    def start_search_run(self, search_run_id: str) -> None: ...
    def record_provider(self, *, search_run_id: str, job_id: str, provider_code: str, operation: str, payload: dict[str, Any], status: str, result_count: int = 0, error: str | None = None) -> None: ...
    def record_progress(self, *, job_id: str, event_type: str, step_code: str, message: str, payload: dict[str, Any] | None = None, progress_percent: float | None = None) -> None: ...
    def update_search_run_progress(self, search_run_id: str, job_id: str, *, candidate_count: int, enriched_count: int, scored_count: int, progress_percent: float) -> None: ...
    def record_evidence(self, *, search_run_id: str, job_id: str, provider_code: str, phase: str, query: str, item: dict[str, Any], attempt_no: int = 1) -> None: ...
    def upsert_candidate(self, *, search_run_id: str, candidate: CompanyCandidate) -> None: ...
    def record_enrichment(self, *, search_run_id: str, job_id: str, candidate: CompanyCandidate, scores: list[DimensionScore], scale_scores: list[DimensionScore], scene_code: str = "S1") -> None: ...
    def finish_search_run(self, search_run_id: str, job_id: str, *, status: str, counts: dict[str, int], error: str | None = None) -> None: ...
    def get_search_run(self, search_run_id: str) -> dict[str, Any] | None: ...
    def is_search_run_cancelled(self, search_run_id: str) -> bool: ...
    def get_run_trace(self, search_run_id: str) -> dict[str, Any] | None: ...

    def list_candidates(self, *, search_run_id: str | None = None, limit: int = 50, analysis_pool: bool = False) -> list[dict[str, Any]]: ...
    def count_candidates(self, *, search_run_id: str | None = None, analysis_pool: bool = False) -> int: ...

    def get_candidate(self, candidate_id: str) -> dict[str, Any] | None: ...
